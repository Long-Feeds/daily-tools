const D2R = Math.PI / 180;
const angSep = (a1, d1, a2, d2) => {
  const a = [Math.cos(d1 * D2R) * Math.cos(a1 * D2R), Math.cos(d1 * D2R) * Math.sin(a1 * D2R), Math.sin(d1 * D2R)];
  const b = [Math.cos(d2 * D2R) * Math.cos(a2 * D2R), Math.cos(d2 * D2R) * Math.sin(a2 * D2R), Math.sin(d2 * D2R)];
  const c = [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
  return Math.atan2(Math.hypot(...c), a[0] * b[0] + a[1] * b[1] + a[2] * b[2]) / D2R;
};
const near = (a, b, tol) => Math.abs(a - b) <= tol;
const wrap180 = (x) => ((x + 540) % 360) - 180;

