  for (const [k, v] of [['v0', '200万'], ['spend', '8万'], ['years', '35'], ['age', '50'], ['target', '50万'], ['floor', '5万'], ['s0', '70'], ['s1', '40'], ['glide', '20'], ['fee', '0.1'], ['sp-band', '25']]) await fill('fl-' + k, v)
