function gcd (a, b) { a = a < 0n ? -a : a; b = b < 0n ? -b : b; while (b) { const t = a % b; a = b; b = t } return a }
function reduce (num, den) {
  const n = BigInt(num), d = BigInt(den)
  if (n === 0n) return '0'
  if (n === d) return '1'
  const g = gcd(n, d)
  return (n / g) + '/' + (d / g)
}
function val (fr) {
  if (fr === '0') return 0
  if (fr === '1') return 1
  const [a, b] = fr.split('/').map(BigInt)
  return Number(a * 9007199254740992n / b) / 9007199254740992
}
function pctShort (p) { return p < 0.005 ? '<1' : p > 0.995 ? '>99' : String(Math.round(p * 100)) }
function pctLong (p) {
  if (p === 0) return '0%'
  if (p === 1) return '100%'
  const v = p * 100
  return (v < 0.1 ? v.toPrecision(2) : v >= 99.9 ? v.toFixed(3) : v.toFixed(1)) + '%'
}
function bigText (s) {
  if (s.length <= 12) return s.replace(/\B(?=(\d{3})+(?!\d))/g, ',')
  return s.charAt(0) + '.' + s.slice(1, 4) + ' × 10^' + (s.length - 1)
}
function adj (i, W, H) {
  const x = i % W, y = (i / W) | 0, out = []
  for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) {
    if (!dx && !dy) continue
    const nx = x + dx, ny = y + dy
    if (nx >= 0 && ny >= 0 && nx < W && ny < H) out.push(ny * W + nx)
  }
  return out
}
